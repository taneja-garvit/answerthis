def abstract_sentence(section: str, starts_with: str) -> str:
    """Return the full sentence of the given abstract section that starts with
    `starts_with`. Raises if absent, so demo evidence cannot drift from the source."""
    text = next(s["text"] for s in PAPER["abstract_sections"] if s["title"] == section)
    start = text.find(starts_with)
    if start == -1:
        raise ValueError(f"Sentence not found in abstract section {section!r}")
    # Sentences in this abstract end with ". " followed by a capital letter.
    end = start
    while True:
        end = text.find(".", end + 1)
        if end == -1 or end + 1 == len(text) or (text[end + 1] == " " and text[end + 2].isupper()):
            break
    return text[start : (len(text) if end == -1 else end + 1)]


