@dataclass(frozen=True)
class SeedResult:
    project_id: uuid.UUID
    draft_id: uuid.UUID
    created: bool


def _normalized_paper() -> dict[str, Any]:
    return dict(PAPER)


async def _existing(session: AsyncSession) -> SeedResult | None:
    row = (
        await session.execute(
            select(Project.id, Draft.id)
            .join(Draft, Draft.project_id == Project.id)
            .where(Project.seed_key == DEMO_SEED_KEY)
            .order_by(Draft.created_at)
            .limit(1)
        )
    ).first()
    return SeedResult(project_id=row[0], draft_id=row[1], created=False) if row else None


async def seed_demo(session: AsyncSession, *, reset: bool = False) -> SeedResult:
    """Create the demo project if it does not exist. Existing demo data, including
    any review decisions, is left alone unless `reset` is set."""
    if reset:
        # Database-level ON DELETE CASCADE removes drafts, claims, evidence,
        # assessments, reviews and review events of the demo project only.
        await session.execute(delete(Project).where(Project.seed_key == DEMO_SEED_KEY))
        await session.commit()
    elif (existing := await _existing(session)) is not None:
        return existing

    await session.execute(
        insert(PaperCache)
        .values(
            doi=PAPER["doi"],
            normalized=_normalized_paper(),
            raw={},
            providers=["crossref", "openalex"],
        )
        .on_conflict_do_nothing(index_elements=[PaperCache.doi])
    )

    project = Project(
        title="Heart-failure remote monitoring — demo review",
        description=(
            "Seeded demo. The draft was written for this demo; evidence is quoted verbatim from "
            "the public abstract of the cited paper (CC BY-NC-ND 4.0). AI assessments are "
            "hand-authored fixtures, not live model output."
        ),
        seed_key=DEMO_SEED_KEY,
    )
    source = Source(
        project=project,
        doi=PAPER["doi"],
        title=PAPER["title"],
        authors=PAPER["authors"],
        journal=PAPER["journal"],
        publication_year=PAPER["publication_year"],
        abstract=PAPER["abstract"],
        open_access_url=PAPER["open_access"]["oa_url"],
        # Open-access full text exists, but only the abstract has been ingested.
        access_status=SourceAccessStatus.ABSTRACT_ONLY,
        source_metadata={
            "volume": PAPER["volume"],
            "issue": PAPER["issue"],
            "pages": PAPER["pages"],
            "published_online": PAPER["published_online"],
            "license": PAPER["license"],
            "open_access": PAPER["open_access"],
            "openalex_id": PAPER["openalex_id"],
            "provenance": PAPER["provenance"],
            "abstract_sections": PAPER["abstract_sections"],
        },
    )
    draft = Draft(
        project=project,
        original_text=DRAFT_TEXT,
        analysis_status=DraftAnalysisStatus.ANALYZED,
        analyzed_at=utcnow(),
    )
    session.add_all([project, source, draft])

    for position, spec in enumerate(DEMO_CLAIMS, start=1):
        claim = Claim(
            draft=draft,
            position=position,
            claim_text=spec["claim_text"],
            original_sentence=spec["original_sentence"],
            citation_marker="[1]",
            status=ClaimStatus.READY,
        )
        claim.citations.append(ClaimSource(source=source, position=0, citation_marker="[1]"))
        evidence = [
            Evidence(
                claim=claim,
                source=source,
                passage=passage,
                location=location,
                access_level=AccessLevel.ABSTRACT,
                retrieval_method="seed_fixture",
                retrieval_score=None,
                rank=rank,
            )
            for rank, (passage, location) in enumerate(spec["evidence"])
        ]
        session.add(claim)
        session.add_all(evidence)
        await session.flush()

        fixture = spec["assessment"]
        session.add(
            Assessment(
                claim=claim,
                verdict=fixture["verdict"],
                confidence_level=fixture["confidence_level"],
                confidence=None,
                issues=[Issue.model_validate(i).model_dump(mode="json") for i in fixture["issues"]],
                explanation=fixture["explanation"],
                suggested_revision=fixture["suggested_revision"],
                evidence_ids=[str(e.id) for e in evidence],
                provider=FIXTURE_PROVIDER,
                model=None,
                prompt_version=None,
                generation_metadata=FIXTURE_METADATA,
            )
        )

    try:
        await session.commit()
    except IntegrityError:
        # A concurrent seed won the race on the unique seed_key.
        await session.rollback()
        existing = await _existing(session)
        if existing is None:
            raise
        return existing
    return SeedResult(project_id=project.id, draft_id=draft.id, created=True)


async def _main(reset: bool) -> None:
    from app.core.config import get_settings
    from app.db.session import Database, create_engine_from_url

    settings = get_settings()
    database = Database(create_engine_from_url(settings.require_database_url(), settings))
    try:
        async with database.sessionmaker() as session:
            result = await seed_demo(session, reset=reset)
    finally:
        await database.dispose()
    state = "created" if result.created else "already present (use --reset to recreate)"
    print(f"Demo project {state}: project_id={result.project_id} draft_id={result.draft_id}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Seed the heart-failure demo project.")
    parser.add_argument("--reset", action="store_true", help="delete and recreate the demo")
    asyncio.run(_main(parser.parse_args().reset))
